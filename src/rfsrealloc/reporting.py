"""LaTeX macros and tables generated from pipeline results."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import pandas as pd


def _macro_name(key: str) -> str:
    """LaTeX macro names may not contain digits; spell them out."""
    digits = {
        "0": "Zero",
        "1": "One",
        "2": "Two",
        "3": "Three",
        "4": "Four",
        "5": "Five",
        "6": "Six",
        "7": "Seven",
        "8": "Eight",
        "9": "Nine",
    }
    out = []
    upper_next = False
    for ch in key:
        if ch == "_":
            upper_next = True
            continue
        ch2 = digits.get(ch, ch)
        out.append(ch2.upper() if upper_next and ch2.isalpha() else ch2)
        upper_next = False
    return "val" + "".join(out)


def _fmt(v: Any, key: str = "") -> str:
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        # calendar years (keys containing "Year") carry no thousands separator
        return str(v) if "Year" in key else f"{v:,}"
    if isinstance(v, float):
        if v == int(v) and abs(v) >= 100:
            return f"{int(v):,}"
        return f"{v:,}"
    s = str(v).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")
    return s


def write_values(values: dict[str, Any], path: Path) -> None:
    lines = ["% Generated by rfsrealloc.pipeline; do not edit.", ""]
    for k in sorted(values):
        lines.append(f"\\newcommand{{\\{_macro_name(k)}}}{{{_fmt(values[k], k)}}}")
    path.write_text("\n".join(lines) + "\n")


def macro_names_in(tex: str) -> set[str]:
    return set(re.findall(r"\\(val[A-Za-z]+)", tex))


def _tex_table(
    df: pd.DataFrame, caption: str, label: str, columns: dict[str, str], floatfmt: dict[str, str] | None = None
) -> str:
    floatfmt = floatfmt or {}
    cols = list(columns)
    header = " & ".join(columns[c] for c in cols) + r" \\"
    body = []
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, float):
                cells.append(format(v, floatfmt.get(c, ".2f")))
            elif isinstance(v, bool) or str(v) in ("True", "False"):
                cells.append("yes" if str(v) == "True" else "no")
            else:
                cells.append(str(v).replace("_", r"\_").replace("%", r"\%"))
        body.append(" & ".join(cells) + r" \\")
    spec = "l" + "r" * (len(cols) - 1)
    return "\n".join(
        [
            r"\begin{table}[htbp]",
            r"\centering",
            r"\caption{" + caption + "}",
            r"\label{" + label + "}",
            r"\footnotesize",
            r"\begin{tabular}{" + spec + "}",
            r"\toprule",
            header,
            r"\midrule",
            *body,
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
        ]
    )


def write_tables(results: Path, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    # Table 1: inputs with sources (from the transcription)
    inp = (
        pd.read_csv(results.parent.parent / "data" / "transcribed" / "entry_a.csv", dtype=str, keep_default_na=False)
        if (results.parent.parent / "data").exists()
        else None
    )
    if inp is not None:
        t = inp[inp["table"] == "set2_inputs"].copy()
        t["value"] = t["value"].astype(float)
        wide = t.pivot_table(index=["variable", "category"], columns="year", values="value").reset_index()
        wide["symbol"] = wide.apply(
            lambda r: r["variable"] + ("\\textsubscript{" + r["category"] + "}" if r["category"] else ""), axis=1
        )
        wide["source"] = "EPA-HQ-OAR-2024-0505-0789, p.~1"
        wide = wide[["symbol", "2026", "2027", "source"]]
        (out / "table_inputs.tex").write_text(
            _tex_table(
                wide,
                "Inputs to the 2026--2027 percentage-standard equations (billion gallons; required volumes in billion gallon-RINs), as published in the docket calculation memorandum.",
                "tab:inputs",
                {"symbol": "Term", "2026": "2026", "2027": "2027", "source": "Source"},
            )
        )
    # Table 2: reconstruction
    rep = pd.read_csv(results / "e1_standards_reproduction.csv")
    rep = rep.copy()
    rep["alternative"] = rep["alternative"].map(
        {
            "set2": "Set 2 rule",
            "equal": "Equal reallocation",
            "all2027": "2027 reallocation",
            "no_srerv": "No reallocation",
        }
    )
    rep["exact_percent"] = rep["exact_percent"].astype(float)
    (out / "table_reconstruction.tex").write_text(
        _tex_table(
            rep[
                [
                    "alternative",
                    "year",
                    "category",
                    "numerator_brins",
                    "denominator_bgal",
                    "exact_percent",
                    "published_percent",
                    "match",
                ]
            ],
            "Reconstructed percentage standards (exact value and published two-decimal value) for the Set 2 rule, the two co-proposed alternatives and the no-reallocation case of docket document EPA-HQ-OAR-2024-0505-0790.",
            "tab:reconstruction",
            {
                "alternative": "Alternative",
                "year": "Year",
                "category": "Category",
                "numerator_brins": "Num. (bn RINs)",
                "denominator_bgal": "Den. (bn gal)",
                "exact_percent": "Exact (\\%)",
                "published_percent": "Publ. (\\%)",
                "match": "Match",
            },
            {"numerator_brins": ".2f", "denominator_bgal": ".2f", "exact_percent": ".4f"},
        )
    )
    # Table 3: uncertainty parameters
    pairs = pd.read_csv(results / "e2_revision_pairs.csv")
    fuel = pd.read_csv(results / "e3_fuel_projection_errors.csv")
    rows = []
    rows.append(
        {
            "parameter": "Exemption revision ratio (reported / petition-based)",
            "n": len(pairs),
            "mean": pairs["ratio"].mean(),
            "sd": pairs["ratio"].std(ddof=1),
            "min": pairs["ratio"].min(),
            "max": pairs["ratio"].max(),
            "basis": "EPA decision documents and dashboard Table SRE-1",
        }
    )
    nr = fuel[~fuel["retroactive"]]
    rows.append(
        {
            "parameter": "Fuel-use ratio (reported / projected), prospective rules",
            "n": len(nr),
            "mean": nr["ratio"].mean(),
            "sd": nr["ratio"].std(ddof=1),
            "min": nr["ratio"].min(),
            "max": nr["ratio"].max(),
            "basis": "EPA dashboard RVO Table 1",
        }
    )
    lags = pd.read_csv(results / "e5_decision_lags.csv")
    vals = json.loads((results / "values.json").read_text())
    y0, y1 = int(vals.get("lagYearsFirst", 2021)), int(vals.get("lagYearsLast", 2025))
    lags = lags[(lags["year"] >= y0) & (lags["year"] <= y1)]
    rows[0]["basis"] = "decisions; SRE-1"
    rows[1]["basis"] = "RVO Table 1"
    rows.append(
        {
            "parameter": f"Decision lag after year end (years), {y0}--{y1} petitions",
            "n": len(lags),
            "mean": lags["lag_years"].mean(),
            "sd": lags["lag_years"].std(ddof=1),
            "min": lags["lag_years"].min(),
            "max": lags["lag_years"].max(),
            "basis": "SRE-3",
        }
    )
    (out / "table_uncertainty.tex").write_text(
        _tex_table(
            pd.DataFrame(rows),
            "Empirical distributions used in the uncertainty model (EPA decision documents and public data tables).",
            "tab:uncertainty",
            {
                "parameter": "Quantity",
                "n": "n",
                "mean": "Mean",
                "sd": "SD",
                "min": "Min",
                "max": "Max",
                "basis": "Basis",
            },
            {"mean": ".3f", "sd": ".3f", "min": ".3f", "max": ".3f"},
        )
    )
    # Full transcription (supporting information), long table
    if inp is not None:
        lines = [
            r"\scriptsize",
            r"\begin{longtable}{p{2.3cm}p{0.7cm}p{1.0cm}p{2.6cm}rp{1.7cm}p{4.6cm}}",
            r"\caption{Transcribed values with sources (entry A).}\\",
            r"\toprule",
            r"Table & Year & Category & Variable & Value & Unit & Source, locator \\",
            r"\midrule",
            r"\endfirsthead",
            r"\toprule",
            r"Table & Year & Category & Variable & Value & Unit & Source, locator \\",
            r"\midrule",
            r"\endhead",
            r"\bottomrule",
            r"\endfoot",
        ]
        for _, r in inp.iterrows():
            cells = [
                str(r["table"]),
                str(r["year"]),
                str(r["category"]),
                str(r["variable"]),
                str(r["value"]),
                str(r["unit"]),
                f"{r['source']}, {r['locator']}",
            ]
            cells = [c.replace("_", r"\_").replace("%", r"\%").replace("&", r"\&").replace("#", r"\#") for c in cells]
            lines.append(" & ".join(cells) + r" \\")
        lines.append(r"\end{longtable}")
        (out / "table_transcription.tex").write_text("\n".join(lines) + "\n")
    # Table 4: accounting
    acc = pd.read_csv(results / "e6_carryover_accounting.csv")
    acc = acc[acc["bank_scenario"] == "baseline"].copy()
    acc["alternative"] = acc["alternative"].map(
        {"set2": "Set 2 rule", "equal": "Equal reallocation", "all2027": "2027 reallocation"}
    )
    (out / "table_accounting.tex").write_text(
        _tex_table(
            acc[
                [
                    "alternative",
                    "year",
                    "rvo_brins",
                    "bank_in_brins",
                    "cap_brins",
                    "carryover_used_brins",
                    "new_rins_required_brins",
                    "bank_out_brins",
                ]
            ],
            "Carryover-RIN accounting (billion RINs) under each alternative, assuming new RIN generation equal to the volume requirement and the baseline bank.",
            "tab:accounting",
            {
                "alternative": "Alternative",
                "year": "Year",
                "rvo_brins": "Obligation",
                "bank_in_brins": "Bank in",
                "cap_brins": "20\\% cap",
                "carryover_used_brins": "Carryover used",
                "new_rins_required_brins": "New RINs required",
                "bank_out_brins": "Bank out",
            },
        )
    )
